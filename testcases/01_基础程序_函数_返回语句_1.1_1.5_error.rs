// 1.5 函数返回类型 + 带表达式return语句
// 【语义错误】函数声明i32返回值，无return语句，缺少返回值
fn program_1_5__1() -> i32 {
    let a:i32=1;
    a
}

// 【语义错误】声明返回i32，return空，类型不一致
fn program_1_5__2() -> i32 {
    return ;
}

// 【语义错误】函数无返回类型，return带i32表达式，类型不匹配
fn program_1_5__3() {
    return 1;
}
